"""Generate auditable JSON, Markdown, CSV, and LaTeX result tables."""

from __future__ import annotations

import csv
import io
from pathlib import Path
from typing import Any, Dict, Iterable, List, Mapping

from ..io import write_json
from .metrics import aggregate_records, score_record


def _fmt(value: Any) -> str:
    if value is None:
        return "--"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def write_evaluation_report(records: Iterable[Mapping[str, Any]], output_dir: str | Path) -> Dict[str, str]:
    target = Path(output_dir)
    target.mkdir(parents=True, exist_ok=True)
    scored = [score_record(record) for record in records]
    aggregate = aggregate_records(scored)
    breakdowns: Dict[str, List[Dict[str, Any]]] = {}
    for field in ("subject", "grade", "question_type", "simulation_type"):
        flattened = []
        for row in scored:
            value = row.get(field)
            if value is None:
                value = (row.get("metadata") or {}).get(field, "unknown")
            flattened.append({**row, field: value})
        breakdowns[field] = aggregate_records(flattened, group_by=("model", "method", field))
    write_json(target / "scored_records.json", scored)
    write_json(target / "aggregate.json", aggregate)
    write_json(target / "breakdowns.json", breakdowns)

    headers = [
        "model", "method", "n", "success_rate", "solution_quality",
        "simulation_correctness", "pedagogical_quality", "overall",
        "mean_estimated_cost_usd",
    ]
    csv_buffer = io.StringIO()
    writer = csv.DictWriter(csv_buffer, fieldnames=headers, extrasaction="ignore")
    writer.writeheader()
    writer.writerows(aggregate)
    (target / "main_results.csv").write_text(csv_buffer.getvalue(), encoding="utf-8")

    breakdown_buffer = io.StringIO()
    breakdown_headers = [
        "group", "value", "model", "method", "n", "success_rate", "solution_quality",
        "simulation_correctness", "pedagogical_quality", "overall",
    ]
    breakdown_writer = csv.DictWriter(breakdown_buffer, fieldnames=breakdown_headers)
    breakdown_writer.writeheader()
    for field, rows in breakdowns.items():
        for row in rows:
            breakdown_writer.writerow(
                {
                    "group": field,
                    "value": row.get(field),
                    **{key: row.get(key) for key in breakdown_headers if key not in {"group", "value"}},
                }
            )
    (target / "breakdowns.csv").write_text(breakdown_buffer.getvalue(), encoding="utf-8")

    markdown = [
        "# K12SimWorld evaluation summary",
        "",
        "Failed generations are included as zero scores; success rate is reported separately.",
        "",
        "| Model | Method | N | Success | Solution | Simulation | Pedagogy | Overall | Cost/problem |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for row in aggregate:
        markdown.append(
            "| " + " | ".join(
                _fmt(row.get(key))
                for key in (
                    "model", "method", "n", "success_rate", "solution_quality",
                    "simulation_correctness", "pedagogical_quality", "overall",
                    "mean_estimated_cost_usd",
                )
            ) + " |"
        )
    (target / "summary.md").write_text("\n".join(markdown) + "\n", encoding="utf-8")

    latex = [
        "% Auto-generated by k12simworld.evaluation.report; do not enter unmeasured values.",
        "\\begin{tabular}{llrrrrrr}",
        "\\toprule",
        "Model & Method & Success & Solution & Simulation & Pedagogy & Overall & Cost \\\\",
        "\\midrule",
    ]
    for row in aggregate:
        cells = [
            str(row.get("model", "")).replace("_", "\\_"),
            str(row.get("method", "")).replace("_", "\\_"),
            *[
                _fmt(row.get(key))
                for key in (
                    "success_rate", "solution_quality", "simulation_correctness",
                    "pedagogical_quality", "overall", "mean_estimated_cost_usd",
                )
            ],
        ]
        latex.append(" & ".join(cells) + " \\\\")
    latex.extend(["\\bottomrule", "\\end{tabular}"])
    (target / "main_results.tex").write_text("\n".join(latex) + "\n", encoding="utf-8")
    return {
        "aggregate": str(target / "aggregate.json"),
        "markdown": str(target / "summary.md"),
        "csv": str(target / "main_results.csv"),
        "breakdowns": str(target / "breakdowns.csv"),
        "latex": str(target / "main_results.tex"),
    }
